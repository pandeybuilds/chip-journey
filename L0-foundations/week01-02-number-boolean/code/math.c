#include <stdio.h>

int main (void) {
    int a = 17;
    int b = 15;

    printf("Sum: %d\n", a + b);
    printf("Difference: %d\n", a - b);
    printf("Product: %d\n", a * b);
    printf("Quotient: %d\n", a / b);
    printf("Module/Remainder: %d\n", a % b);
    return 0;
}
